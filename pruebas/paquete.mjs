import assert from 'node:assert/strict';
import fs from 'node:fs';
import {gramosAMililitros,mililitrosAGramos,mostrarCantidad,calcularNutrientes,calcularReceta,clasificarReceta} from '../motor_avanzi.mjs';
import {prepararIngredientes} from '../catalogo_avanzi.mjs';
const cat=JSON.parse(fs.readFileSync(new URL('../datos/ingredientes.json',import.meta.url),'utf8')).ingredientes;
const compat=JSON.parse(fs.readFileSync(new URL('../datos/compatibilidad.json',import.meta.url),'utf8'));
const visuales=prepararIngredientes(cat,compat);
for(const ingrediente of visuales)assert.ok(fs.existsSync(new URL('../'+ingrediente.dibujo.replace(/^\.\//,''),import.meta.url)),`Falta dibujo: ${ingrediente.id}`);
assert.match(visuales.find(i=>i.id==='pasta-curry').dibujo,/condimentos\.svg$/);
const {recetas}=JSON.parse(fs.readFileSync(new URL('../datos/recetas.json',import.meta.url),'utf8'));
const by=Object.fromEntries(cat.map(x=>[x.id,x]));
assert.equal(cat.length,200);
assert.equal(recetas.length,39);
assert.equal(Math.round(gramosAMililitros(100,1.03)),97);
assert.equal(Math.round(mililitrosAGramos(100,1.03)),103);
assert.match(mostrarCantidad(100,'g',by.leche),/97 ml/);
assert.equal(by['aceite-oliva'].por100g.kcal,884);
assert.equal(by['aceite-oliva'].por100g.grasasG,100);
let r=calcularNutrientes({porciones:1,ingredientes:[{ingredienteId:'aceite-oliva',cantidad:10,unidad:'g'}]},cat);
assert.equal(r.completo,true);
assert.equal(r.porPorcion.kcal,88.4);
assert.equal(r.porPorcion.grasasG,10);
assert.equal(r.porPorcion.proteinasG,0);
const unknown={porciones:1,ingredientes:[{ingredienteId:'huevo',cantidad:1,unidad:'unidad'}]};
r=calcularNutrientes(unknown,cat); assert.equal(r.completo,false); assert.equal(r.porPorcion,null);
const missing={porciones:null,ingredientes:[{ingredienteId:'aceite-oliva',cantidad:10,unidad:'g'}]};
r=calcularNutrientes(missing,cat); assert.equal(r.completo,false); assert.equal(r.porPorcion,null);
const chick=recetas.find(r=>r.id==='pdr-cooked-chickpeas');
r=calcularNutrientes(chick,cat);
assert.equal(r.completo,true);
const cooked=calcularNutrientes({porciones:1,ingredientes:[{ingredienteId:'garbanzos',gramosComestibles:100,perfilNutricionalUsado:'garbanzos_cocidos',noUsarValoresSecosParaCocidos:true}]},cat);
assert.equal(cooked.porPorcion.kcal,164);
const dryInCooked=calcularNutrientes({porciones:1,ingredientes:[{ingredienteId:'garbanzos',gramosComestibles:100,noUsarValoresSecosParaCocidos:true}]},cat);
assert.equal(dryInCooked.completo,false);
const tea=recetas.find(r=>r.id==='pdr-indian-tea');
r=calcularNutrientes(tea,cat); assert.equal(r.completo,true);
assert.ok(r.porPorcion.kcal>0);
assert.equal(calcularReceta(tea,by).estado,'estimacion');
const hojas=tea.ingredientes.find(i=>i.ingredienteId==='te-negro');
assert.equal(hojas.gramosComestibles,0);
assert.equal(hojas.motivoExclusion,'insumo_no_ingerido');
const teaSinHojas={...tea,ingredientes:tea.ingredientes.filter(i=>i.ingredienteId!=='te-negro')};
assert.deepEqual(calcularNutrientes(teaSinHojas,cat).porPorcion,r.porPorcion);
const exclusionInjustificada={porciones:1,ingredientes:[{ingredienteId:'huevo',incluidoEnCalculo:false}]};
assert.equal(calcularNutrientes(exclusionInjustificada,cat).completo,false);
assert.deepEqual(clasificarReceta({tiempoMinutos:19,ingredientes:[{ingredienteId:'pasta-seca'}]},cat),['rapidas','veggie','pastas']);
assert.deepEqual(clasificarReceta({tiempoMinutos:20,ingredientes:[{ingredienteId:'pasta-seca'}]},cat),['veggie','pastas']);
assert.deepEqual(clasificarReceta({tiempoMinutos:19,ingredientes:[{ingredienteId:'huevo'}]},cat),['rapidas']);
const completos=recetas.filter(rec=>calcularNutrientes(rec,cat).completo).length;
assert.equal(completos,39,`Unexpected completed estimate count: ${completos}`);
const esperadas={'pdr-basic-waffles':20,'pdr-pasta-navy-style':2,'pdr-refried-beans':2,'pdr-indian-tea':4,'pdr-pasta-arrabbiata':5,'pdr-cacio-e-pepe':4,'pdr-danish-pancake':6,'pdr-oats':1};
for(const [id,porciones] of Object.entries(esperadas)){
  const rec=recetas.find(r=>r.id===id);
  assert.equal(rec.porciones,porciones,id);
  const calculo=calcularNutrientes(rec,cat);
  assert.equal(calculo.completo,true,id);
  for(const k of ['kcal','proteinasG','carbohidratosG','grasasG']){
    assert.ok(Math.abs(calculo.porPorcion[k]-rec.nutricion.porPorcion[k])<=0.11,`${id} - ${k} inconsistente`);
    assert.ok(Math.abs(calculo.total[k]-rec.nutricion.totalRecetaEstimado[k])<=0.11,`${id} - total ${k} inconsistente`);
  }
}
const daneses=recetas.find(r=>r.id==='pdr-danish-pancake');
assert.equal(daneses.ingredientes.find(i=>i.ingredienteId==='azucar').gramosComestibles,19);
const beans=recetas.find(r=>r.id==='pdr-refried-beans');
assert.ok(beans.ingredientes.find(i=>i.ingredienteId==='porotos').texto.includes('cocidos'));
assert.equal(beans.ingredientes.find(i=>i.ingredienteId==='porotos').perfilNutricionalUsado,'porotos_cocidos');
console.log(`OK: ${recetas.length} recetas, ${cat.length} ingredientes, ${completos} estimaciones completas; conversiones, aceite, legumbres, cantidades incompletas y categorias.`);
